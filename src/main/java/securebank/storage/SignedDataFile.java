package securebank.storage;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Objects;
import securebank.exception.DataIntegrityException;
import securebank.security.IntegrityService;

/*
 * Handles reading and writing text files protected by an HMAC
 * The file contains a header, the saved records, and an HMAC on the last line
 * The HMAC helps detect changes made to the file outside the application
 *
 * Example file structure:
 * # securebank users v1
 * record|record|record
 * #hmac=BASE64
 */
public final class SignedDataFile {

    private static final String MAC_PREFIX = "#hmac=";

    private final Path path;
    private final String header;
    private final IntegrityService integrity;
    private boolean acceptedUnsigned;

    public SignedDataFile(Path path, String header, IntegrityService integrity) {
        this.path = Objects.requireNonNull(path, "path");
        this.header = Objects.requireNonNull(header, "header");
        this.integrity = Objects.requireNonNull(integrity, "integrity");
    }

    public String name() {
        return path.getFileName().toString();
    }

    /*
     * Reads the file, verifies its HMAC, and returns its records
     * If the file does not exist yet, an empty list is returned
     */
    public List<String> readLines() {
        if (!Files.exists(path)) {
            return List.of();
        }

        String content;
        try {
            // Use consistent line endings so verification works across systems
            content = Files.readString(path, StandardCharsets.UTF_8).replace("\r\n", "\n");
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }

        // Separate the file contents from the HMAC stored on the last line
        int macStart = content.lastIndexOf("\n" + MAC_PREFIX) + 1;
        String body = macStart > 0 ? content.substring(0, macStart) : content;
        String mac = macStart > 0
                ? content.substring(macStart + MAC_PREFIX.length()).strip()
                : null;

        // Reject files with an invalid or missing HMAC unless the configured
        // setup allows unsigned files to be accepted during initial migration
        if (!integrity.verify(body, mac)) {
            if (!integrity.isTrustingUnsignedFiles()) {
                throw new DataIntegrityException(
                        name() + " has been modified outside the application (HMAC check failed).");
            }

            // Let the repository know that the file must be signed when saved
            acceptedUnsigned = true;
        }

        String[] lines = body.split("\n", -1);

        // Make sure the file belongs to the expected data type and version
        if (!header.equals(lines[0])) {
            throw new DataIntegrityException(name() + " has an unexpected header.");
        }

        List<String> records = new ArrayList<>();

        // Skip the header and ignore empty lines when collecting records
        for (int i = 1; i < lines.length; i++) {
            if (!lines[i].isEmpty()) {
                records.add(lines[i]);
            }
        }

        return records;
    }

    /*
     * Indicates whether the last read accepted a file without a valid HMAC
     * Repositories use this to decide whether the file needs to be signed again
     */
    public boolean acceptedUnsigned() {
        return acceptedUnsigned;
    }

    /*
     * Builds the file contents, signs them, and writes the result atomically
     * Records containing newlines or starting with '#' are rejected to prevent
     * records from being split across lines or confused with file metadata
     */
    public void writeLines(List<String> records) throws IOException {
        StringBuilder body = new StringBuilder(header).append('\n');

        for (String r : records) {
            if (r.indexOf('\n') >= 0 || r.indexOf('\r') >= 0 || r.startsWith("#")) {
                throw new IllegalArgumentException("Record contains forbidden characters");
            }

            body.append(r).append('\n');
        }

        // Sign the complete header and record section before saving the file
        String signed = body + MAC_PREFIX + integrity.sign(body.toString()) + "\n";

        SecureFiles.writeAtomically(path, signed);

        // The file now has a valid HMAC generated by the application
        acceptedUnsigned = false;
    }
}